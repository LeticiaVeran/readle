CREATE TABLE LIVRO (
    id_livro       INTEGER GENERATED BY DEFAULT AS IDENTITY,
    titulo         VARCHAR(200)  NOT NULL,
    isbn           VARCHAR(13)   NOT NULL,
    ano_publicacao SMALLINT      NOT NULL,
    numero_paginas INTEGER       NOT NULL,
    sinopse        VARCHAR(2000),
    url_capa       VARCHAR(255),
    CONSTRAINT pk_livro PRIMARY KEY (id_livro),
    CONSTRAINT uq_livro_isbn UNIQUE (isbn),
    CONSTRAINT ck_livro_isbn CHECK (char_length(isbn) IN (10, 13)),
    CONSTRAINT ck_livro_paginas CHECK (numero_paginas > 0)
);

CREATE TABLE GENERO (
    id_genero INTEGER GENERATED BY DEFAULT AS IDENTITY,
    nome      VARCHAR(50) NOT NULL,
    CONSTRAINT pk_genero PRIMARY KEY (id_genero)
);

CREATE TABLE USUARIO (
    id_usuario    INTEGER GENERATED BY DEFAULT AS IDENTITY,
    nome_usuario  VARCHAR(30)  NOT NULL,
    email         VARCHAR(120) NOT NULL,
    senha_hash    VARCHAR(255) NOT NULL,
    data_cadastro DATE         NOT NULL DEFAULT CURRENT_DATE,
    nome          VARCHAR(100) NOT NULL,
    CONSTRAINT pk_usuario PRIMARY KEY (id_usuario),
    CONSTRAINT uq_usuario_nome_usuario UNIQUE (nome_usuario),
    CONSTRAINT uq_usuario_email UNIQUE (email)
);

CREATE TABLE GRUPO_LEITURA (
    id_grupo              INTEGER GENERATED BY DEFAULT AS IDENTITY,
    nome                  VARCHAR(100) NOT NULL,
    descricao             VARCHAR(500),
    privacidade           VARCHAR(20)  NOT NULL DEFAULT 'Público',
    data_criacao          DATE         NOT NULL DEFAULT CURRENT_DATE,
    situacao              VARCHAR(20)  NOT NULL DEFAULT 'Aguardando membros',
    FK_LIVRO_id_livro     INTEGER      NOT NULL,
    FK_USUARIO_id_usuario INTEGER      NOT NULL,  -- the group organizer
    CONSTRAINT pk_grupo_leitura PRIMARY KEY (id_grupo),
    CONSTRAINT ck_grupo_privacidade CHECK (privacidade IN ('Público', 'Privado')),
    CONSTRAINT ck_grupo_situacao CHECK (situacao IN ('Aguardando membros', 'Ativo', 'Encerrado'))
);

CREATE TABLE AVALIACAO_RESENHA (
    id_avaliacao          INTEGER GENERATED BY DEFAULT AS IDENTITY,
    nota                  SMALLINT NOT NULL,
    texto_resenha         VARCHAR(4000),
    data_publicacao       DATE     NOT NULL DEFAULT CURRENT_DATE,
    FK_LIVRO_id_livro     INTEGER  NOT NULL,
    FK_USUARIO_id_usuario INTEGER  NOT NULL,
    CONSTRAINT pk_avaliacao_resenha PRIMARY KEY (id_avaliacao),
    CONSTRAINT uq_avaliacao_usuario_livro UNIQUE (FK_USUARIO_id_usuario, FK_LIVRO_id_livro),
    CONSTRAINT ck_avaliacao_nota CHECK (nota BETWEEN 1 AND 5)
);

CREATE TABLE ITEM_ESTANTE (
    id_item               INTEGER GENERATED BY DEFAULT AS IDENTITY,
    status_leitura        VARCHAR(20) NOT NULL,
    data_inclusao         DATE        NOT NULL DEFAULT CURRENT_DATE,
    data_inicio           DATE,
    data_conclusao        DATE,
    FK_LIVRO_id_livro     INTEGER     NOT NULL,
    FK_USUARIO_id_usuario INTEGER     NOT NULL,
    CONSTRAINT pk_item_estante PRIMARY KEY (id_item),
    CONSTRAINT uq_item_estante_usuario_livro UNIQUE (FK_USUARIO_id_usuario, FK_LIVRO_id_livro),
    CONSTRAINT ck_item_estante_status CHECK (status_leitura IN ('Lido', 'Lendo', 'Quero Ler', 'Abandonado')),
    CONSTRAINT ck_item_estante_datas CHECK (data_conclusao IS NULL OR data_inicio IS NULL OR data_conclusao >= data_inicio)
);

CREATE TABLE ETAPA_LEITURA (
    id_etapa                  INTEGER GENERATED BY DEFAULT AS IDENTITY,
    titulo                    VARCHAR(100) NOT NULL,
    ordem                     SMALLINT     NOT NULL,
    descricao                 VARCHAR(500),
    data_limite               DATE         NOT NULL,
    FK_GRUPO_LEITURA_id_grupo INTEGER      NOT NULL,
    CONSTRAINT pk_etapa_leitura PRIMARY KEY (id_etapa),
    CONSTRAINT uq_etapa_grupo_ordem UNIQUE (FK_GRUPO_LEITURA_id_grupo, ordem),
    CONSTRAINT ck_etapa_ordem CHECK (ordem > 0)
);

CREATE TABLE NOTIFICACAO (
    id_notificacao        INTEGER GENERATED BY DEFAULT AS IDENTITY,
    tipo                  VARCHAR(20)  NOT NULL,
    texto                 VARCHAR(300) NOT NULL,
    data_hora             TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    lida                  BOOLEAN      NOT NULL DEFAULT FALSE,
    FK_USUARIO_id_usuario INTEGER      NOT NULL,
    CONSTRAINT pk_notificacao PRIMARY KEY (id_notificacao),
    CONSTRAINT ck_notificacao_tipo CHECK (tipo IN ('Convite', 'Mensagem', 'Grupo', 'Prazo'))
);

CREATE TABLE MENSAGEM (
    id_mensagem               INTEGER GENERATED BY DEFAULT AS IDENTITY,
    conteudo                  VARCHAR(2000) NOT NULL,
    data_hora_publicacao      TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    data_hora_edicao          TIMESTAMP,
    situacao                  VARCHAR(20)   NOT NULL DEFAULT 'Visível',
    FK_ETAPA_LEITURA_id_etapa INTEGER       NOT NULL,
    FK_MEMBRO_GRUPO_id_membro INTEGER       NOT NULL,
    CONSTRAINT pk_mensagem PRIMARY KEY (id_mensagem),
    CONSTRAINT ck_mensagem_situacao CHECK (situacao IN ('Visível', 'Oculta')),
    CONSTRAINT ck_mensagem_edicao CHECK (data_hora_edicao IS NULL OR data_hora_edicao >= data_hora_publicacao)
);

CREATE TABLE MEMBRO_GRUPO (
    id_membro                 INTEGER GENERATED BY DEFAULT AS IDENTITY,
    funcao                    VARCHAR(20) NOT NULL DEFAULT 'Membro',
    status_participacao       VARCHAR(20) NOT NULL DEFAULT 'Ativo',
    data_entrada              DATE        NOT NULL DEFAULT CURRENT_DATE,
    FK_USUARIO_id_usuario     INTEGER     NOT NULL,
    FK_GRUPO_LEITURA_id_grupo INTEGER     NOT NULL,
    CONSTRAINT pk_membro_grupo PRIMARY KEY (id_membro),
    CONSTRAINT uq_membro_usuario_grupo UNIQUE (FK_USUARIO_id_usuario, FK_GRUPO_LEITURA_id_grupo),
    CONSTRAINT ck_membro_funcao CHECK (funcao IN ('Membro', 'Moderador')),
    CONSTRAINT ck_membro_status CHECK (status_participacao IN ('Convidado', 'Solicitado', 'Ativo', 'Removido'))
);

CREATE TABLE PROGRESSO_ETAPA (
    id_progresso              INTEGER GENERATED BY DEFAULT AS IDENTITY,
    concluida                 BOOLEAN NOT NULL DEFAULT FALSE,
    data_confirmacao          DATE,
    FK_ETAPA_LEITURA_id_etapa INTEGER NOT NULL,
    FK_MEMBRO_GRUPO_id_membro INTEGER NOT NULL,
    CONSTRAINT pk_progresso_etapa PRIMARY KEY (id_progresso),
    CONSTRAINT uq_progresso_membro_etapa UNIQUE (FK_MEMBRO_GRUPO_id_membro, FK_ETAPA_LEITURA_id_etapa),
    -- the confirmation date exists only when the stage is finished
    CONSTRAINT ck_progresso_confirmacao CHECK (concluida = (data_confirmacao IS NOT NULL))
);

CREATE TABLE ESCREVE (
